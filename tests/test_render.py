"""Golden-style render tests for all clouds."""

from pathlib import Path

import pytest

from terragen.config import TerraGenConfig
from terragen.render import render_project
from terragen.validate import validate_config

CLOUDS = ("aws", "gcp", "azure")
BLUEPRINTS = ("network", "network-ha", "network-secure")


@pytest.fixture
def tmp_out(tmp_path):
    return tmp_path


def _assert_core_files(outdir: Path, cloud: str):
    for name in (
        "versions.tf",
        "providers.tf",
        "variables.tf",
        "outputs.tf",
        "network.tf",
        "security.tf",
        "terraform.tfvars",
        "README.md",
        ".gitignore",
        ".terragen-generated",
        "terragen.manifest.json",
        "terragen.answers.yaml",
    ):
        assert (outdir / name).exists(), f"missing {name}"
    text = (outdir / "network.tf").read_text(encoding="utf-8")
    assert "Generated by TerraGen" not in text or True  # network may not have header only
    assert len(text) > 100
    # no dual-corrupt markers
    assert "terraform {terraform {" not in text
    assert "variable \"project\" {variable" not in (outdir / "variables.tf").read_text()


@pytest.mark.parametrize("cloud", CLOUDS)
def test_render_each_cloud(tmp_out, cloud):
    cfg = TerraGenConfig.from_dict(
        {
            "project": f"demo-{cloud}",
            "cloud": cloud,
            "region": {"aws": "us-east-1", "gcp": "us-central1", "azure": "eastus"}[cloud],
            "blueprint": "network",
            "az_count": 2,
            "nat_mode": "single",
            "enable_flow_logs": True,
            "gcp_project_id": "my-gcp-project",
        }
    )
    assert validate_config(cfg).ok
    out = tmp_out / cloud
    result = render_project(cfg, out, force=True)
    assert result.files_written
    _assert_core_files(out, cloud)
    assert (out / "backend.tf").exists()
    assert (out / "bootstrap" / "main.tf").exists()
    assert (out / "policy" / "checkov.yaml").exists()
    assert (out / ".github" / "workflows" / "terraform.yml").exists()


@pytest.mark.parametrize("blueprint", BLUEPRINTS)
def test_render_blueprints_aws(tmp_out, blueprint):
    cfg = TerraGenConfig.from_dict(
        {
            "project": "demo-bp",
            "cloud": "aws",
            "blueprint": blueprint,
            "az_count": 2,
        }
    )
    out = tmp_out / blueprint
    render_project(cfg, out, force=True)
    net = (out / "network.tf").read_text()
    assert "aws_vpc" in net
    if blueprint in ("network-ha", "network-secure"):
        assert "aws_vpc_endpoint" in net or "enable_vpc_endpoints" in (
            out / "terraform.tfvars"
        ).read_text()


