def test_refuse_overwrite_non_terragen(tmp_out):
    out = tmp_out / "existing"
    out.mkdir()
    (out / "notes.txt").write_text("user file")
    cfg = TerraGenConfig.from_dict({"project": "demo-x", "cloud": "aws"})
    with pytest.raises(FileExistsError):
        render_project(cfg, out, force=False)


def test_force_overwrite(tmp_out):
    out = tmp_out / "regen"
    cfg = TerraGenConfig.from_dict({"project": "demo-y", "cloud": "aws"})
    render_project(cfg, out, force=True)
    render_project(cfg, out, force=True)  # marker present; force also ok
    assert (out / ".terragen-generated").exists()


def test_dry_run_writes_nothing(tmp_out):
    out = tmp_out / "dry"
    cfg = TerraGenConfig.from_dict({"project": "demo-dry", "cloud": "aws"})
    result = render_project(cfg, out, dry_run=True)
    assert not out.exists()
    assert result.files_written


def test_custom_subnets(tmp_out):
    cfg = TerraGenConfig.from_dict(
        {
            "project": "demo-custom",
            "cloud": "aws",
            "az_count": 2,
            "vpc_cidr": "10.0.0.0/16",
            "public_subnets": ["10.0.0.0/24", "10.0.1.0/24"],
            "private_subnets": ["10.0.10.0/24", "10.0.11.0/24"],
        }
    )
    out = tmp_out / "custom"
    render_project(cfg, out, force=True)
    tfvars = (out / "terraform.tfvars").read_text()
    assert "10.0.0.0/24" in tfvars
    assert "10.0.10.0/24" in tfvars


